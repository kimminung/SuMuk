import Foundation
import CoreGraphics

/// Decorative style attached to the artwork or to a single family. Not part of the mathematics.
nonisolated struct InkStyle: Equatable, Sendable {
    var hex: String = "141414"
    var width: Double = 0.6
    var alpha: Double = 0.85
    var fill: Bool = false

    var rgb: (Double, Double, Double) {
        var v: UInt64 = 0
        Scanner(string: hex).scanHexInt64(&v)
        let r = Double((v >> 16) & 0xFF) / 255, g = Double((v >> 8) & 0xFF) / 255, b = Double(v & 0xFF) / 255
        return (r, g, b)
    }
}

/// `let name = value in [lo, hi]` — a scrubbable scalar exposed as a slider.
nonisolated struct LetVariable: Equatable, Sendable, Identifiable {
    var id: String { name }
    let name: String
    var value: Double
    let range: ClosedRange<Double>
    let line: Int
}

nonisolated struct IntegerRange: Equatable, Sendable {
    let variable: String
    let lower: Int
    let upper: Int
    var count: Int { max(0, upper - lower + 1) }
}

nonisolated struct RealRange: Equatable, Sendable {
    let variable: String
    let lower: Double
    let upper: Double
    let samples: Int
}

/// One family of elements generated by a single parameter.
nonisolated enum Family: Equatable, Sendable {
    case segments(range: IntegerRange, from: (MathExpr, MathExpr), to: (MathExpr, MathExpr), ink: InkStyle?)
    case circles(range: IntegerRange, center: (MathExpr, MathExpr), radius: MathExpr, ink: InkStyle?)
    case curve(range: RealRange, x: MathExpr, y: MathExpr, ink: InkStyle?)

    static func == (lhs: Family, rhs: Family) -> Bool {
        switch (lhs, rhs) {
        case let (.segments(r1, f1, t1, i1), .segments(r2, f2, t2, i2)):
            return r1 == r2 && f1.0 == f2.0 && f1.1 == f2.1 && t1.0 == t2.0 && t1.1 == t2.1 && i1 == i2
        case let (.circles(r1, c1, rad1, i1), .circles(r2, c2, rad2, i2)):
            return r1 == r2 && c1.0 == c2.0 && c1.1 == c2.1 && rad1 == rad2 && i1 == i2
        case let (.curve(r1, x1, y1, i1), .curve(r2, x2, y2, i2)):
            return r1 == r2 && x1 == x2 && y1 == y2 && i1 == i2
        default: return false
        }
    }

    var elementCount: Int {
        switch self {
        case .segments(let r, _, _, _): return r.count
        case .circles(let r, _, _, _): return r.count
        case .curve(let r, _, _, _): return r.samples
        }
    }

    var kindName: String {
        switch self {
        case .segments: return "선분"
        case .circles: return "원"
        case .curve: return "곡선"
        }
    }

    var ink: InkStyle? {
        switch self {
        case .segments(_, _, _, let i), .circles(_, _, _, let i), .curve(_, _, _, let i): return i
        }
    }
}

/// A parsed SuMuk Script. The script text itself remains the source of truth; this is a view of it.
nonisolated struct Artwork: Equatable, Sendable {
    var canvas: CGSize? = nil
    var ink = InkStyle()
    var lets: [LetVariable] = []
    var families: [Family] = []
    var definitions: [String: FunctionDefinition] = [:]

    var elementCount: Int { families.reduce(0) { $0 + $1.elementCount } }

    static let maxFamilies = 20
    static let maxElements = 1_000_000
    static let maxScriptLength = 50_000
}
